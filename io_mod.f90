MODULE io_mod
  USE data_mod
  USE assembly_mod
CONTAINS

      SUBROUTINE INPUT_DATA()
!
!  NE= NUMBER OF BOUNDARY ELEMENTS
!  L = NUMBER OF INTERNAL POINTS
!  CP= P-WAVE VELOCITY
!  CS= S-WAVE VELOCITY
!  RO= DENSITY
!  NFR= NUMBER OF FREQUENCIES TO BE ANALYSED
!  AFR= ARRAY FOR STORAGE OF FREQUENCIES
!  FR= FREQUENCY
!  GE= SHEAR MODULUS
!  XNU= POISSON RATIO
!

!  READ FREQUENCIES
!
      READ(INP,*) (AFR(I),I=1,NFR)
      WRITE(IPR,400) (AFR(I),I=1,NFR)
  400 FORMAT(/2X,'FREQUENCIES'/5(2X,G14.7))
!
!  READ BOUNDARY NODES COORDINATES
!
      N=2*NE
      WRITE(IPR,500)
      READ(INP,*) (X(I),Y(I),I=1,N)
      DO 10 I=1,N
   10 WRITE(IPR,240) I,X(I),Y(I)
  500 FORMAT(//2X,'BOUNDARY NODES COORDINATES'///4X, &
      'NODE',10X,'X',18X,'Y'/)
  240 FORMAT(5X,I3,2(5X,E14.7))
!
!  READ BOUNDARY CONDITIONS IN BC(I) VECTOR, IF KODE(I)=0
!  THE BC(I) VALUE IS A KNOWN DISPLACEMENT; IF KODE(I)=1 THE
!  BC(I) VALUE IS A KNOWN TRACTION.
!  SIX BOUNDARY CONDITIONS ARE READ PER ELEMENT.
!  NODES BETWEEN TWO ELEMENTS MAY HAVE TWO DIFFERENT VALUES
!  OF THE TRACTION BUT ONLY ONE VALUE OF THE DISPLACEMENT.
!
      WRITE(IPR,800)
  800 FORMAT(//2X,'BOUNDARY CONDITIONS'//11X, &
      '-----FIRST NODE------',3X,'-----SECOND NODE-----',3X, &
      '-----THIRD NODE------'/13X,'PRESCRIBED',14X, &
      'PRESCRIBED',14X,'PRESCRIBED'/1X,'ELEMENT',8X,'VALUE', &
      7X,'CODE',8X,'VALUE',7X,'CODE',8X,'VALUE',7X,'CODE')
      DO 30 I=1,NE
      READ(INP,*) (KODE(6*I-6+2*J-1),BC(6*I-6+2*J-1),J=1,3)
      WRITE(IPR,950) I,(BC(6*I-6+2*J-1),KODE(6*I-6+2*J-1),J=1,3)
      READ(INP,*) (KODE(6*I-6+2*J),BC(6*I-6+2*J),J=1,3)
   30 WRITE(IPR,960) I,(BC(6*I-6+2*J),KODE(6*I-6+2*J),J=1,3)
  950 FORMAT(1X,I3,' X',1X,3(G10.3,',',G10.3,2X,I1))
  960 FORMAT(1X,I3,' Y',1X,3(G10.3,',',G10.3,2X,I1))
!
!  READ INTERNAL POINTS COORDINATES
!
      IF(L.EQ.0) RETURN
      READ(INP,*) (CX(I),CY(I),I=1,L)
      RETURN
      END

      SUBROUTINE INTER4(FI,DFI,KODE,CX,CY,X,Y,DSOL)
!
!  THIS SUBROUTINE COMPUTES THE VALUES OF STRESSES AND DISPLACEMENTS AT
!  INTERNAL POINTS.
!
      COMPLEX FI(1),DFI(1),GW(2,6),HW(2,6),DSOL(1)
      COMPLEX CH
      DIMENSION X(1),Y(1),KODE(1),CX(1),CY(1),HS(2,6)
!       COMMON N,L,CP,CS,GE,RO,XNU,FR,INP,IPR
!
!  REARRANGE FI AND DFI ARRAYS TO STORE ALL THE VALUES OF THE
!  DISPLACEMENT IN FI AND ALL THE VALUES TRACTION IN DFI
!
      NE=N/2
      DO 180 I=1,NE
      DO 170 J=1,6
      IF(KODE(6*I-6+J)) 110,110,170
  110 IF((I-NE).NE.0 .OR. J.LT.5) GO TO 125
      IF(KODE(J-4)) 114,114,113
  113 CH=FI(J-4)*GE
      FI(J-4)=DFI(6*I-6+J)
      DFI(6*I-6+J)=CH
      GO TO 170
  114 DFI(6*I-6+J)=DFI(J-4)
      GO TO 170
  125 IF(I.EQ.1 .OR. J.GT.2 .OR. KODE(6*I-8+J).EQ.1) GO TO 130
      DFI(6*I-6+J)=DFI(6*I-8+J)
      GO TO 170
  130 CH=FI(4*I-4+J)*GE
      FI(4*I-4+J)=DFI(6*I-6+J)
      DFI(6*I-6+J)=CH
  170 CONTINUE
  180 CONTINUE
!
!  COMPUTE THE VALUES OF DISPLACEMENT AT INTERNAL POINTS
!
      IF(L.EQ.0) RETURN
      DO 240 K=1,L
      DSOL(2*K-1)=(0.,0.)
      DSOL(2*K)=(0.,0.)
      DO 230 I=1,NE
      CALL EXTIN4(CX(K),CY(K),X(2*I-1),Y(2*I-1),X(2*I),Y(2*I), &
      X(2*I+1),Y(2*I+1),HW,GW,HS)
      DO 220 J=1,6
      IJ4=4*I-4+J
      IF(IJ4.GT.(4*NE)) IJ4=J-4
      DSOL(2*K-1)=DSOL(2*K-1)+GW(1,J)*DFI(6*I-6+J)- &
      (HW(1,J)+HS(1,J))*FI(IJ4)
  220 DSOL(2*K)=DSOL(2*K)+GW(2,J)*DFI(6*I-6+J)-(HW(2,J)+HS(2,J))*FI(IJ4)
  230 CONTINUE
  240 CONTINUE
   50 RETURN
      END

      SUBROUTINE OUTPUT4(X,Y,FI,DFI,CX,CY,DSOL)
!
!  THIS SUBROUTINE PRINTS THE VALUES OF THE DISPLACEMENTS
!  AND TRACTIONS AT BOUNDARY NODES. IT ALSO PRINTS THE VALUES
!  OF DISPLACEMENTS AT INTERNAL POINTS
!
      DIMENSION X(1),Y(1),CX(1),CY(1)
      COMPLEX FI(1),DFI(1),DSOL(1),CP,CS,GE
!       COMMON N,L,CP,CS,GE,RO,XNU,FR,INP,IPR
      NE=N/2
      WRITE(IPR,50)
   50 FORMAT(' ',79('*'))
      WRITE(IPR,700) FR
  700 FORMAT(30X,'FREQUENCY =',G14.7/)
      WRITE(IPR,100)
  100 FORMAT(' ',79('*')//1X,'RESULTS'//2X,'BOUNDARY NODES'///6X &
      ,'X',12X,'Y',11X,'DISPLACEMENT X',10X,'DISPLACEMENT Y'/)
      DO 10 I=1,N
   10 WRITE(IPR,200) X(I),Y(I),FI(2*I-1),FI(2*I)
  200 FORMAT(2(2X,G11.4),2(1X,G11.4,',',G11.4))

      WRITE(IPR,150)
  150 FORMAT(///6X,'X',12X,'Y',13X,'TRACTION X',14X,'TRACTION Y'/)
      WRITE(IPR,250) X(1),Y(1),DFI(6*NE-1),DFI(6*NE)
      WRITE(IPR,260) X(1),Y(1),DFI(1),DFI(2)
      WRITE(IPR,270) X(2),Y(2),DFI(3),DFI(4)
      DO 15 I=2,NE
      WRITE(IPR,250) X(2*I-1),Y(2*I-1),DFI(6*I-7),DFI(6*I-6)
      WRITE(IPR,260) X(2*I-1),Y(2*I-1),DFI(6*I-5),DFI(6*I-4)
   15 WRITE(IPR,270) X(2*I),Y(2*I),DFI(6*I-3),DFI(6*I-2)
  250 FORMAT(6X,'BEFORE THE NODE'/2(2X,G11.4),2(1X,G11.4,',',G11.4)/)
  260 FORMAT(6X,'AFTER THE NODE'/2(2X,G11.4),2(1X,G11.4,',',G11.4)/)
  270 FORMAT(1X,'BEFORE AND AFTER THE NODE'/2(2X,G11.4), &
      2(1X,G11.4,',',G11.4)/)
      IF(L.EQ.0) RETURN
      WRITE(IPR,300)
  300 FORMAT(///2X,'INTERNAL POINTS DISPLACEMENTS'// &
      6X,'X',12X,'Y',11X,'DISPLACEMENT X',10X,'DISPLACEMENT Y'/)
      DO 20 K=1,L
   20 WRITE(IPR,200)CX(K),CY(K),DSOL(2*K-1),DSOL(2*K)
   30 WRITE(IPR,50)
      RETURN
      END

END MODULE io_mod
