      SUBROUTINE GHMAT4(X,Y,G,H,FI,DFI,KODE,NX,NX1)
      INTEGER :: LL, I, NODO, JJ, K, LLL, JC, J, II, NN, NE
!
!  THIS SUBROUTINE COMPUTES THE G AND H MATRICES AND FORMS
!  THE SYSTEM A X = F READY TO BE SOLVED
!  H IS A SQUARE MATRIX (4*NE,4*NE); G IS RECTANGULAR (4*NE,6*NE)
!

      COMPLEX FI(1),DFI(1),G(NX,NX1),H(NX,NX),HW(2,6),GW(2,6),CH
      
      DIMENSION X(1),Y(1),KODE(1),HS(2,6)
!       COMMON N,L,CP,CS,GE,RO,XNU,FR,INP,IPR
      NN=2*N
      NE=N/2
      DO 20 I=1,NN
      DO 11 J=1,NN
   11 H(I,J)=(0.,0.)
      DO 12 J=1,3*N
   12 G(I,J)=(0.,0.)
   20 CONTINUE
      X(N+1)=X(1)
      Y(N+1)=Y(1)
!
!  COMPUTE THE GW, HW AND HS MATRICES FOR EACH COLLOCATION
!  POINT AND EACH BOUNDARY ELEMENT
!
!$OMP PARALLEL DO PRIVATE(LL, I, NODO, HW, GW, HS, JJ, K, LLL, JC, J, II)
      DO 100 LL=1,N
      DO 90 I=1,N-1,2
      IF((LL-I)*(LL-I-1)*(LL-I-2)*(LL-I+N-2)) 22,21,22
   21 NODO=LL-I+1
      IF((LL.EQ.1).AND.(I.EQ.N-1)) NODO=NODO+N
      CALL EXTIN4(X(LL),Y(LL),X(I),Y(I),X(I+1),Y(I+1),X(I+2),Y(I+2), &
      HW,GW,HS)
      CALL LOCIN4(X(I),Y(I),X(I+1),Y(I+1),X(I+2),Y(I+2),GW,NODO)
      GO TO 34
   22 CALL EXTIN4(X(LL),Y(LL),X(I),Y(I),X(I+1),Y(I+1),X(I+2),Y(I+2), &
      HW,GW,HS)
!
!  PLUG THE GW, HW AND HS MATRICES INTO THE GENERAL G AND H MATRICES
!  BY USING THE  2*2 SUBMATRICES CORRESPONDING TO EACH NODE.
!
   34 DO 80 JJ=1,3
!
!  PLUG THE GW MATRICES
!
      DO 70 K=1,2
      LLL=2*LL-2+K
      DO 70 JC=1,2
      J=2*(JJ-1)+JC
      G(LLL,3*I-3+J)=G(LLL,3*I-3+J)+GW(K,J)
!
!  PLUG THE HW AND HS MATRICES
!
      II=I
      IF((I.EQ.N-1).AND.(JJ.EQ.3)) II=-1
!
      IF(LL.EQ.II-1+JJ) GO TO 66
!
!  THE 2*2 SUBMATRIX DOES NOT BELONG TO THE DIAGONAL
!
      H(LLL,2*II-2+J)=H(LLL,2*II-2+J)+HW(K,J)+HS(K,J)
      H(LLL,2*LL-2+JC)=H(LLL,2*LL-2+JC)-HS(K,J)
      GO TO 70
!
!  THE 2*2 SUBMATRIX BELONGS TO THE DIAGONAL
!
   66 H(LLL,2*LL-2+JC)=H(LLL,2*LL-2+JC)+HW(K,J)

   70 CONTINUE
   80 CONTINUE
   90 CONTINUE

!
!  ADD ONE TO THE DIAGONAL COEFFICIENTS FOR
!  EXTERNAL PROBLEMS.
!
      IF(REAL(H(2*LL-1,2*LL-1))) 95,100,100
   95 H(2*LL-1,2*LL-1)=H(2*LL-1,2*LL-1)+1.
      H(2*LL,2*LL)=H(2*LL,2*LL)+1.
  100 CONTINUE
!
!  REORDER THE COLUMNS OF THE SYSTEM OF EQUATIONS IN ACCORDANCE
!  WITH THE BOUNDARY CONDITIONS AND FORM SYSTEM MATRIX A WHICH
!  IS STORED IN H
!
      DO 180 I=1,NE
      DO 170 J=1,6
      IF(KODE(6*I-6+J)) 110,110,170
  110 IF((I-NE).NE.0 .OR. J.LT.5) GO TO 125
      IF(KODE(J-4)) 115,115,113
  113 DO 114 K=1,NN
      CH=H(K,J-4)
      H(K,J-4)=-G(K,6*I-6+J)*GE
  114 G(K,6*I-6+J)=-CH
      GO TO 170
  115 DO 116 K=1,NN
      H(K,J-4)=H(K,J-4)-G(K,6*I-6+J)*GE
  116 G(K,6*I-6+J)=(0.,0.)
      GO TO 170
  125 IF(I.EQ.1 .OR. J.GT.2 .OR. KODE(6*I-8+J).EQ.1) GO TO 130
      DO 129 K=1,NN
      H(K,4*I-4+J)=H(K,4*I-4+J)-G(K,6*I-6+J)*GE
  129 G(K,6*I-6+J)=(0.,0.)
      GO TO 170
  130 DO 132 K=1,NN
      CH=H(K,4*I-4+J)
      H(K,4*I-4+J)=-G(K,6*I-6+J)*GE
  132 G(K,6*I-6+J)=-CH
  170 CONTINUE
  180 CONTINUE
!
!  FORM THE RIGHT HAND SIDE VECTOR F WHICH IS STORED IN FI
!
      DO 190 I=1,NN
      FI(I)= (0.,0.)
      DO 185 J=1,6*NE
  185 FI(I)=FI(I)+G(I,J)*DFI(J)
  190 CONTINUE
      RETURN
      END

      SUBROUTINE EXTIN4(XP,YP,X1,Y1,X2,Y2,X3,Y3,HW,GW,HS)
!
!  THIS SUBROUTINE COMPUTES THE HW, HS AND GW MATRICES
!  THAT RELATE A NODE (XP,YP) WITH A BOUNDARY
!  ELEMENT USING GAUSS QUADRATURE.
!
!  RA           = RADIUS
!  RD1,RD2,RDN  = RADIUS DERIVATIVES
!  ETA1,ETA2    = COMPONENTS OF THE UNIT NORMAL TO THE ELEMENT
!  XCO,YCO      = INTEGRATION POINT ALONG THE ELEMENT
!  XJA          = JACOBIAN
!
      COMPLEX GW(2,6),HW(2,6),F0CS,F0CP,F1CS,F1CP,F2CS,F2CP
      COMPLEX GW11,GW12,GW21,GW22,HD11,HD12,HD21,HD22
      COMPLEX ZCS,ZCP,PSI,CAP,DPSI,DCAP,XIM,DE2
      COMPLEX F0MCS,F1MCS,F2MCS,F0MCP,F1MCP,F2MCP
      COMPLEX AA,BB
      DIMENSION GI(10),OME(10),HS(2,6)
!       COMMON N,L,CP,CS,GE,RO,XNU,FR,INP,IPR
      DATA GI/0.9739065285,-0.9739065285,0.8650633666,-0.8650633666 &
             ,0.6794095683,-0.6794095682,0.4333953941,-0.4333953941 &
             ,0.1488743389,-0.1488743389/
      DATA OME/0.0666713443,0.0666713443,0.1494513491,0.1494513491 &
              ,0.2190863625,0.2190863625,0.2692667193,0.2692667193 &
              ,0.2955242247,0.2955242247/

      DO 30 I=1,2
      DO 20 J=1,6
      HS(I,J)=0.
      HW(I,J)=(0.,0.)
   20 GW(I,J)=(0.,0.)
   30 CONTINUE

      A=X3-2*X2+X1
      B=(X3-X1)/2
      C=Y3-2*Y2+Y1
      D=(Y3-Y1)/2
      DE=4.*3.1415926*(1-XNU)
      DE2=CS*CS*RO*6.2831852

      DO 40 I=1,10
!
!  COMPUTE THE VALUES OF THE SHAPE FUNCTIONS AT THE
!  INTEGRATION POINTS
!
      F1=GI(I)*(GI(I)-1)*0.5
      F2=1.-GI(I)**2
      F3=GI(I)*(GI(I)+1)*0.5
!
!  COMPUTE GEOMETRICAL PARAMETERS AT THE INTEGRATION POINTS
!
      XCO=X1*F1+X2*F2+X3*F3
      YCO=Y1*F1+Y2*F2+Y3*F3
      XJA=SQRT((GI(I)*A+B)**2+(GI(I)*C+D)**2)
      ETA1=(GI(I)*C+D)/XJA
      ETA2=-(GI(I)*A+B)/XJA
      RA=SQRT((XP-XCO)**2+(YP-YCO)**2)
      RD1=(XCO-XP)/RA
      RD2=(YCO-YP)/RA
      RDN=RD1*ETA1+RD2*ETA2
!
!  COMPUTE KERNELS FOR THE STATIC PART OF THE H MATRIX
!
      HS11=-RDN*((1-2*XNU)+2*RD1**2)/(RA*DE)
      HS12=-(RDN*2*RD1*RD2+(1-2*XNU)*(ETA1*RD2-ETA2*RD1))/(RA*DE)
      HS21=-(RDN*2*RD1*RD2+(1-2*XNU)*(ETA2*RD1-ETA1*RD2))/(RA*DE)
      HS22=-RDN*((1-2*XNU)+2*RD2**2)/(RA*DE)
!
!  COMPUTE KERNELS FOR THE G MATRIX
!
      ZCS=CMPLX(0.,1.)
      ZCP=CMPLX(0.,1.)
      ZCS=ZCS*FR*RA/CS
      ZCP=ZCP*FR*RA/CP
      CALL BESSEL(ZCS,F0CS,F1CS,F2CS,F0MCS,F1MCS,F2MCS)
      CALL BESSEL(ZCP,F0CP,F1CP,F2CP,F0MCP,F1MCP,F2MCP)
      CAP=F2CS-CS**2*F2CP/CP**2
      PSI=F0CS+(F1CS-F1CP*CS/CP)/ZCS

      GW11=(PSI-CAP*RD1**2)/DE2
      GW12=-CAP*RD1*RD2/DE2
      GW21=GW12
      GW22=(PSI-CAP*RD2**2)/DE2

!
!  COMPUTE KERNELS FOR THE DIFFERENCE BETWEEN THE DINAMIC AND THE
!  STATIC H MATRIX USING THE NON-SINGULAR PARTS OF THE BESSEL FUNCTIONS
!
      AA=ZCS**2/(2.*RA)*(CLOG(ZCS/2.)+0.07722156)
      BB=ZCP**2*CS**2/(2.*RA*CP**2)*(CLOG(ZCP/2.)+0.07722156)

      XIM=CMPLX(0.,FR)
      CAP=F2MCS-CS**2*F2MCP/CP**2
      DPSI=(-F1MCS*(2*CS-(FR*RA)**2/CS)+F1MCP*CS**2*2/CP)/(XIM*RA**2)- &
      (F0MCS-F0MCP*CS**2/CP**2)/RA-AA
      DCAP=(-F1MCS/CS+F1MCP*CS**2/CP**3)*XIM-(F2MCS*2.-F2MCP*2*CS**2/ &
      CP**2)/RA-AA+BB

      HD12=((DPSI-CAP/RA)*RD2*ETA1-2.*CAP*(ETA2*RD1-2.*RD1*RD2*RDN)/RA &
      -2.*DCAP*RD1*RD2*RDN+((CP/CS)**2-2.)*(DPSI-DCAP-CAP/RA)*RD1*ETA2) &
      /6.2831852

      HD21=((DPSI-CAP/RA)*RD1*ETA2-2.*CAP*(ETA1*RD2-2.*RD1*RD2*RDN)/RA &
      -2.*DCAP*RD1*RD2*RDN+((CP/CS)**2-2.)*(DPSI-DCAP-CAP/RA)*RD2*ETA1) &
      /6.2831852

      HD11=((DPSI-CAP/RA)*(RDN+RD1*ETA1)-2.*CAP*(ETA1*RD1-2*RD1**2*RDN)/ &
      RA-2.*DCAP*RD1**2*RDN+((CP/CS)**2-2.)*(DPSI-DCAP-CAP/RA)*RD1*ETA1) &
      /6.2831852

      HD22=((DPSI-CAP/RA)*(RDN+RD2*ETA2)-2.*CAP*(ETA2*RD2-2*RD2**2*RDN)/ &
      RA-2.*DCAP*RD2**2*RDN+((CP/CS)**2-2.)*(DPSI-DCAP-CAP/RA)*RD2*ETA2) &
      /6.2831852


!
!  COMPUTE GW, HS AND HW MATRICES
!
      GW(1,1)=GW(1,1)+GW11*OME(I)*XJA*F1
      GW(1,2)=GW(1,2)+GW12*OME(I)*XJA*F1
      GW(2,1)=GW(2,1)+GW21*OME(I)*XJA*F1
      GW(2,2)=GW(2,2)+GW22*OME(I)*XJA*F1
      GW(1,3)=GW(1,3)+GW11*OME(I)*XJA*F2
      GW(1,4)=GW(1,4)+GW12*OME(I)*XJA*F2
      GW(2,3)=GW(2,3)+GW21*OME(I)*XJA*F2
      GW(2,4)=GW(2,4)+GW22*OME(I)*XJA*F2
      GW(1,5)=GW(1,5)+GW11*OME(I)*XJA*F3
      GW(1,6)=GW(1,6)+GW12*OME(I)*XJA*F3
      GW(2,5)=GW(2,5)+GW21*OME(I)*XJA*F3
      GW(2,6)=GW(2,6)+GW22*OME(I)*XJA*F3

      HS(1,1)=HS(1,1)+HS11*OME(I)*XJA*F1
      HS(1,2)=HS(1,2)+HS12*OME(I)*XJA*F1
      HS(2,1)=HS(2,1)+HS21*OME(I)*XJA*F1
      HS(2,2)=HS(2,2)+HS22*OME(I)*XJA*F1
      HS(1,3)=HS(1,3)+HS11*OME(I)*XJA*F2
      HS(1,4)=HS(1,4)+HS12*OME(I)*XJA*F2
      HS(2,3)=HS(2,3)+HS21*OME(I)*XJA*F2
      HS(2,4)=HS(2,4)+HS22*OME(I)*XJA*F2
      HS(1,5)=HS(1,5)+HS11*OME(I)*XJA*F3
      HS(1,6)=HS(1,6)+HS12*OME(I)*XJA*F3
      HS(2,5)=HS(2,5)+HS21*OME(I)*XJA*F3
      HS(2,6)=HS(2,6)+HS22*OME(I)*XJA*F3

      HW(1,1)=HW(1,1)+HD11*OME(I)*XJA*F1
      HW(1,2)=HW(1,2)+HD12*OME(I)*XJA*F1
      HW(2,1)=HW(2,1)+HD21*OME(I)*XJA*F1
      HW(2,2)=HW(2,2)+HD22*OME(I)*XJA*F1
      HW(1,3)=HW(1,3)+HD11*OME(I)*XJA*F2
      HW(1,4)=HW(1,4)+HD12*OME(I)*XJA*F2
      HW(2,3)=HW(2,3)+HD21*OME(I)*XJA*F2
      HW(2,4)=HW(2,4)+HD22*OME(I)*XJA*F2
      HW(1,5)=HW(1,5)+HD11*OME(I)*XJA*F3
      HW(1,6)=HW(1,6)+HD12*OME(I)*XJA*F3
      HW(2,5)=HW(2,5)+HD21*OME(I)*XJA*F3
   40 HW(2,6)=HW(2,6)+HD22*OME(I)*XJA*F3
      RETURN
      END

      SUBROUTINE LOCIN4(XG1,YG1,XG2,YG2,XG3,YG3,GW,NODO)
!
!  THIS SUBROUTINE COMPUTES THE GW MATRIX WHEN THE COLLOCATION
!  POINT IS ONE OF THE NODES OF THE INTEGRATION ELEMENT.
!  THE COEFFICIENTS ARE COMPUTED BY NUMERICAL INTEGRATION:
!  THE NON SINGULAR PART IS COMPUTED USING STANDARD GAUSS QUADRATURE,
!  THE LOGARITHMIC PART IS COMPUTED USING A SPECIAL QUADRATURE FORMULA.
!
      COMPLEX GW(2,6),F0CS,F0CP,F1CS,F1CP,F2CS,F2CP
      COMPLEX ZCS,ZCP,PSI,CAP,CONT1,TERNS,S1,S2,S3
      COMPLEX F0MCS,F0MCP,F1MCS,F1MCP,F2MCS,F2MCP
      
      DIMENSION GI(10),OME(10),GIL(10),OMEL(10)
!       COMMON N,L,CP,CS,GE,RO,XNU,FR,INP,IPR
!
!  DATA FOR THE GAUSS QUADRATURE
!
      DATA GI/0.9739065285,-0.9739065285,0.8650633666,-0.8650633666 &
             ,0.6794095682,-0.6794095682,0.4333953941,-0.4333953941, &
              0.1488743389,-0.1488743389/
      DATA OME/0.0666713443,0.0666713443,0.1494513491,0.1494513491 &
              ,0.2190863625,0.2190863625,0.2692667193,0.2692667193, &
               0.2955242247,0.2955242247/
!
!  DATA FOR THE SPECIAL QUADRATURE
!
      DATA GIL/0.0090426309,0.0539712662,0.1353118246,0.2470524162 &
              ,0.3802125396,0.5237923179,0.6657752055,0.7941904160, &
               0.8981610912,0.9688479887/
      DATA OMEL/0.1209551319,0.1863635425,0.1956608732,0.1735771421 &
               ,0.1356956729,0.0936467585,0.0557877273,0.0271598109, &
                0.0095151826,0.0016381576/
!
!  SET LOCAL COORDINATES SYSTEM
!
      GOTO(1,2,3),NODO
    1 X3=XG3-XG1
      Y3=YG3-YG1
      X2=XG2-XG1
      Y2=YG2-YG1
      A1=(X3-2*X2)*0.5
      B1=X2
      A2=(Y3-2*Y2)*0.5
      B2=Y2
      GO TO 4
    2 X3=XG3-XG2
      Y3=YG3-YG2
      X1=XG1-XG2
      Y1=YG1-YG2
      A1=X1+X3
      B1=X3-X1
      A2=Y1+Y3
      B2=Y3-Y1
      GO TO 4
    3 X2=XG2-XG3
      Y2=YG2-YG3
      X1=XG1-XG3
      Y1=YG1-YG3
      A1=(X1-2*X2)*0.5
      B1=-X2
      A2=(Y1-2*Y2)*0.5
      B2=-Y2
    4 CONTINUE
!
      DO 10 I=1,2
      DO 10 J=1,6
   10 GW(I,J)=(0.,0.)
      A=A1**2+A2**2
      B=2*(A1*B1+A2*B2)
      C=B1**2+B2**2
      CONT1=(3-4*XNU)/(8.*3.1415926*GE*(1-XNU))
      DO 250 I=1,10


!
!  COMPUTE SHAPE FUNCTIONS FOR NUMERICAL INTEGRATION
!
      F3=0.5*GI(I)*(GI(I)+1.)
      F2=1.-GI(I)**2
      F1=0.5*GI(I)*(GI(I)-1.)
      FL3=GIL(I)*(2.*GIL(I)-1.)
      FL2=4.*GIL(I)*(1.-GIL(I))
      FL1=(GIL(I)-1.)*(2.*GIL(I)-1.)
      FLN3=0.5*GIL(I)*(GIL(I)+1.)
      FLN2=1.-GIL(I)**2
      FLN1=0.5*GIL(I)*(GIL(I)-1.)
!
!  COMPUTE GW COEFFICIENTS
!
      T1=((A1*GI(I)+B1)**2)/((A2*GI(I)+B2)**2 + (A1*GI(I)+B1)**2)
      T2=((A2*GI(I)+B2)**2)/((A2*GI(I)+B2)**2 + (A1*GI(I)+B1)**2)
      T3=(A1*GI(I)+B1)*(A2*GI(I)+B2)/((A1*GI(I)+B1)**2+(A2*GI(I)+B2)**2)
      RANS=SQRT((A1*GI(I)+B1)**2+(A2*GI(I)+B2)**2)

      GO TO(50,60,70) NODO

   50 XJA1=SQRT((4*A1*GIL(I)-2*A1+0.5*X3)**2+(4*A2*GIL(I)-2*A2+0.5*Y3)** &
      2)*2
      XJA2=SQRT((A1*GI(I)*2+0.5*X3)**2+(A2*GI(I)*2+0.5*Y3)**2)
      RA=RANS*ABS(1.+GI(I))
      ZCS=CMPLX(0.,1.)
      ZCP=CMPLX(0.,1.)
      ZCS=ZCS*FR*RA/CS
      ZCP=ZCP*FR*RA/CP
      CALL BESSEL(ZCS,F0CS,F1CS,F2CS,F0MCS,F1MCS,F2MCS)
      CALL BESSEL(ZCP,F0CP,F1CP,F2CP,F0MCP,F1MCP,F2MCP)
      CAP=F2CS-CS**2*F2CP/CP**2
      PSI=F0CS+(F1CS-F1CP*CS/CP)/ZCS
      TERNS=PSI/(6.2831852*GE*CONT1)+ALOG(ABS(1.+GI(I))/2)
      S3=CONT1*(FL3*XJA1*OMEL(I)+F3*XJA2*TERNS*OME(I))
      S2=CONT1*(FL2*XJA1*OMEL(I)+F2*XJA2*TERNS*OME(I))
      S1=CONT1*(FL1*XJA1*OMEL(I)+F1*XJA2*TERNS*OME(I))
      GO TO 200

   60 XJA1=SQRT((0.5*B1-A1*GIL(I))**2+(0.5*B2-A2*GIL(I))**2)
      XJA11=SQRT((0.5*B1+A1*GIL(I))**2+(0.5*B2+A2*GIL(I))**2)
      XJA2=SQRT((0.5*B1+A1*GI(I))**2+(0.5*B2+A2*GI(I))**2)
      RA=RANS*ABS(GI(I))/2
      ZCS=CMPLX(0.,1.)
      ZCP=CMPLX(0.,1.)
      ZCS=ZCS*FR*RA/CS
      ZCP=ZCP*FR*RA/CP
      CALL BESSEL(ZCS,F0CS,F1CS,F2CS,F0MCS,F1MCS,F2MCS)
      CALL BESSEL(ZCP,F0CP,F1CP,F2CP,F0MCP,F1MCP,F2MCP)
      CAP=F2CS-CS**2*F2CP/CP**2
      PSI=F0CS+(F1CS-F1CP*CS/CP)/ZCS
      TERNS=PSI/(6.2831852*GE*CONT1)+ALOG(ABS(GI(I)))
      S3=CONT1*((FLN1*XJA1+FLN3*XJA11)*OMEL(I)+F3*XJA2*TERNS*OME(I))
      S2=CONT1*(FLN2*(XJA1+XJA11)*OMEL(I)+F2*XJA2*TERNS*OME(I))
      S1=CONT1*((FLN3*XJA1+FLN1*XJA11)*OMEL(I)+F1*XJA2*TERNS*OME(I))
      GO TO 200

   70 XJA1=SQRT((2*A1-4*A1*GIL(I)-0.5*X1)**2+(2*A2-4*A2*GIL(I)-0.5*Y1)** &
      2)*2
      XJA2=SQRT((2*A1*GI(I)-0.5*X1)**2+(2*A2*GI(I)-0.5*Y1)**2)
      RA=RANS*ABS(GI(I)-1.)
      ZCS=CMPLX(0.,1.)
      ZCP=CMPLX(0.,1.)
      ZCS=ZCS*FR*RA/CS
      ZCP=ZCP*FR*RA/CP
      CALL BESSEL(ZCS,F0CS,F1CS,F2CS,F0MCS,F1MCS,F2MCS)
      CALL BESSEL(ZCP,F0CP,F1CP,F2CP,F0MCP,F1MCP,F2MCP)
      CAP=F2CS-CS**2*F2CP/CP**2
      PSI=F0CS+(F1CS-F1CP*CS/CP)/ZCS
      TERNS=PSI/(6.2831852*GE*CONT1)+ALOG(ABS(GI(I)-1.)/2)
      S3=CONT1*(FL1*XJA1*OMEL(I)+F3*XJA2*TERNS*OME(I))
      S2=CONT1*(FL2*XJA1*OMEL(I)+F2*XJA2*TERNS*OME(I))
      S1=CONT1*(FL3*XJA1*OMEL(I)+F1*XJA2*TERNS*OME(I))

  200 GW(1,5)= GW(1,5)+S3-(CAP/(6.2831852*GE))*F3*T1*XJA2*OME(I)
      GW(1,3)= GW(1,3)+S2-(CAP/(6.2831852*GE))*F2*T1*XJA2*OME(I)
      GW(1,1)= GW(1,1)+S1-(CAP/(6.2831852*GE))*F1*T1*XJA2*OME(I)
      GW(1,6)= GW(1,6)-(CAP/(6.2831852*GE))*T3*XJA2*F3*OME(I)
